"""Noisy execution of the Hadamard-test circuits with SpinPulse (arXiv:2601.10435).

Pipeline per circuit block (prep, controlled step):
  HardwareSpecs.gate_transpile -> native gates (rx, ry, rz, rzz; RZZ echoed by SpinPulse)
  PulseCircuit.from_circuit    -> Gaussian pulses
  attach_time_traces + to_circuit -> one noisy unitary per noise realization.

Trajectories
------------
A run measuring g(k tau) is: prep, then k controlled steps, starting at t = 0. For noise
realization r we generate one continuous noise trace and integrate the blocks on
consecutive slices of it: prep on [0, T_p), step m on [T_p + m T_s, T_p + (m+1) T_s).
Reading g after every step yields g(k tau) for k = 0..K from one trajectory. Each prefix
has exactly the noise statistics of a separate run of that length, so the realization-
averaged g(k tau) are unbiased; only their realization-to-realization fluctuations are
correlated across k. The blocks are compiled separately, i.e. no gate cancellation across
step boundaries (consistent with the no-fast-forwarding choice in evolution.py).
g(0) = 1 by definition (S_00 needs no circuit).

Noise sources and rates
-----------------------
Rates Gamma = 1/T* in 1/us for: quasi-static, white and pink (1/f) qubit-frequency noise
(SpinPulse T2S) and pink exchange noise (SpinPulse TJS). Several sources at once are
summed (independent processes) in a duck-typed container exposing what
PulseCircuit.attach_time_traces reads. Every trace is generated by SpinPulse once per
(realization, source) at a reference rate and rescaled by (Gamma/Gamma_ref)^p (p = 1/2 for
white noise, 1 otherwise), which equals regenerating it with the same seed. This gives
common random numbers for the sensitivity analysis. Both facts are tested in tests/test_noisy.py.

SpinPulse correction
--------------------
SpinPulse 1.1.3 applies each operand's local terms (detuning ramps, frequency noise) to
the *other* qubit during two-qubit layers (see spinpulse_patch.py). The corrected
PulseLayer.to_circuit is applied at import and again in every worker process; pass
spinpulse_fix=False to noisy_g_samples to reproduce SpinPulse as released.

Expectation values are exact per realization (no shot noise).
"""

from __future__ import annotations

