from dataclasses import dataclass, field, replace

import numpy as np
from joblib import Parallel, delayed
from qiskit import QuantumCircuit
from qiskit.providers.fake_provider import GenericBackendV2
from qiskit.quantum_info import Operator
from qiskit.transpiler import PassManager
from qiskit.transpiler.passes import Optimize1qGatesDecomposition
from qiskit.transpiler.preset_passmanagers import generate_preset_pass_manager
from spin_pulse import ExperimentalEnvironment, HardwareSpecs, PulseCircuit, Shape
from spin_pulse.environment.noise import NoiseType
from spin_pulse.transpilation.passes.rzz_echo import RZZEchoPass

from . import spinpulse_patch
from .evolution import controlled_step_circuit, g_from_state, prep_circuit
from .hamiltonian import H2Problem

spinpulse_patch.apply()  # on by default; see the module docstring

SOURCES = ("quasistatic", "white", "pink", "exchange")
_EXPONENT = {"quasistatic": 1.0, "white": 0.5, "pink": 1.0, "exchange": 1.0}
_GAMMA_REF = 1e-4  # 1/ns (T* = 10 us); traces are rescaled from this
PINK_SEGMENT_NS = 2**18  # 262 us >= longest simulated run (prep + 63 steps = 237 us)


# ---------------------------------------------------------------------------
# Hardware model: SpinPulse "ParametrizingfromQPUSpecs" example (1 ns step;
# t_z = 0.1 us, t_x = t_zz = 1 us Gaussian pulses).
# ---------------------------------------------------------------------------


def make_hardware_specs(num_qubits: int = 2, t_z=100.0, t_x=1000.0, t_zz=1000.0, coeff_duration=5,
                        ramp_duration=5, dynamical_decoupling=None, transpile_seed: int | None = 0) -> HardwareSpecs:
    """SpinPulse HardwareSpecs from gate times (ns), with deterministic transpilation.

    SpinPulse 1.1.3 builds an unseeded GenericBackendV2 whose random error rates steer
    Optimize1qGatesDecomposition, so compiled circuits vary between runs. With a seed the
    pass managers are rebuilt exactly as in HardwareSpecs.__init__ on a seeded backend.
    """
    s_z, s_x, s_zz = t_z / coeff_duration, t_x / coeff_duration, t_zz / coeff_duration
    hs = HardwareSpecs(
        num_qubits=num_qubits,
        B_field=np.pi / (np.sqrt(2 * np.pi) * s_x),
        delta=np.pi / (np.sqrt(2 * np.pi) * s_z),
        J_coupling=np.pi / (2 * np.sqrt(2 * np.pi) * s_zz),
        rotation_shape=Shape.GAUSSIAN,
        ramp_duration=ramp_duration,
        coeff_duration=coeff_duration,
        dynamical_decoupling=dynamical_decoupling,
    )
    if transpile_seed is not None:
        backend = GenericBackendV2(num_qubits=num_qubits, coupling_map=hs.coupling_map,
                                   basis_gates=hs.basis_gates, seed=transpile_seed)
        hs.first_pass = generate_preset_pass_manager(target=backend.target, optimization_level=0)
        hs.second_pass = PassManager([RZZEchoPass(), Optimize1qGatesDecomposition(target=backend.target)])
    return hs


@dataclass(frozen=True)
class NoiseConfig:
    """Noise rates Gamma = 1/T* in 1/us. Zero switches a source off."""

    quasistatic: float = 0.0
    white: float = 0.0
    pink: float = 0.0
    exchange: float = 0.0

    def as_dict(self) -> dict[str, float]:
        return {s: getattr(self, s) for s in SOURCES}

    def with_(self, **kw) -> "NoiseConfig":
        return replace(self, **kw)

    def scaled(self, factor: float) -> "NoiseConfig":
        return NoiseConfig(**{s: v * factor for s, v in self.as_dict().items()})

    @staticmethod
    def only(source: str, gamma: float) -> "NoiseConfig":
        return NoiseConfig(**{source: gamma})


#: SpinPulse example values (pink T2* = 10 us, pink TJ* = 5 us; F1 > 0.9995, F2 ~ 0.994 there).
SPINPULSE_EXAMPLE_POINT = NoiseConfig(pink=1 / 10, exchange=1 / 5)
#: Operating point: SpinPulse example point + quasi-static T2* = 50 us
#: and white T2* = 1 ms (these two are assumptions of the demo).
DEFAULT_OPERATING_POINT = NoiseConfig(quasistatic=1 / 50, white=1 / 1000, pink=1 / 10, exchange=1 / 5)


# ---------------------------------------------------------------------------
# Compilation
# ---------------------------------------------------------------------------


@dataclass
class Block:
    logical: QuantumCircuit
    isa: QuantumCircuit
    pulse: PulseCircuit

    @property
    def duration_ns(self) -> int:
        return int(self.pulse.duration)


def compile_block(circ: QuantumCircuit, hs: HardwareSpecs) -> Block:
    isa = hs.gate_transpile(circ)
    if isa.layout is not None and list(isa.layout.final_index_layout()) != list(range(circ.num_qubits)):
        raise RuntimeError("non-trivial layout: noise traces would be attached to permuted qubits")
    return Block(circ, isa, PulseCircuit.from_circuit(isa, hs))


@dataclass
class CompiledHadamardTest:
    problem: H2Problem
    tau: float
    hs: HardwareSpecs
    prep: Block
    step: Block

    def run_duration_ns(self, k: int) -> int:
        return self.prep.duration_ns + k * self.step.duration_ns

    def resources(self, k: int) -> dict:
        """Native-gate counts and duration of the run measuring g(k tau)."""
        ops_p, ops_s = dict(self.prep.isa.count_ops()), dict(self.step.isa.count_ops())
        keys = set(ops_p) | set(ops_s)
        ops = {g: ops_p.get(g, 0) + k * ops_s.get(g, 0) for g in keys}
        return {"k": k, "ops": ops, "rzz": ops.get("rzz", 0), "duration_us": self.run_duration_ns(k) / 1e3,
                "evolution_time": k * self.tau}


def compile_hadamard_test(problem: H2Problem, tau: float, hs: HardwareSpecs | None = None) -> CompiledHadamardTest:
    hs = hs or make_hardware_specs(2)
    return CompiledHadamardTest(problem, tau, hs, compile_block(prep_circuit(problem), hs),
                                compile_block(controlled_step_circuit(problem, tau), hs))


# ---------------------------------------------------------------------------
# Noise traces
# ---------------------------------------------------------------------------


class _Trace:
    __slots__ = ("values",)

    def __init__(self, values):
        self.values = values


class TraceBundle:
    """Stand-in for ExperimentalEnvironment with summed traces (what attach_time_traces reads)."""

    def __init__(self, hs: HardwareSpecs, freq: list[np.ndarray], coupling: list[np.ndarray]):
        self.hardware_specs = hs
        self.only_idle = False
        self.duration = int(min(len(v) for v in freq + coupling))
        self.time_traces = [_Trace(v) for v in freq]
        self.time_traces_coupling = [_Trace(v) for v in coupling]


def _seed(base_seed: int, realization: int, source_idx: int) -> int:
    return int(np.random.SeedSequence([base_seed, realization, source_idx]).generate_state(1, np.uint32)[0])


@dataclass
class UnitTraces:
    freq: dict[str, list[np.ndarray]]
    coupling: list[np.ndarray]


def generate_unit_traces(hs: HardwareSpecs, length: int, realization: int, base_seed: int = 2026) -> UnitTraces:
    """One realization of every source, generated by SpinPulse at Gamma_ref."""
    t_ref = 1.0 / _GAMMA_REF
    pow2 = 1 << int(np.ceil(np.log2(max(length, 2))))
    qs = ExperimentalEnvironment(hs, NoiseType.QUASISTATIC, T2S=t_ref, duration=pow2, segment_duration=pow2,
                                 seed=_seed(base_seed, realization, 0))
    wh = ExperimentalEnvironment(hs, NoiseType.WHITE, T2S=t_ref, duration=pow2, segment_duration=1,
                                 seed=_seed(base_seed, realization, 1))
    # Fixed 1/f segment for every run length, so both algorithms see the same spectrum
    # (low-frequency cutoff 1/PINK_SEGMENT_NS = 3.8 kHz).
    if length > PINK_SEGMENT_NS:
        raise ValueError(f"run of {length} ns exceeds the fixed 1/f segment of {PINK_SEGMENT_NS} ns")
    pink_len = PINK_SEGMENT_NS  # identical 1/f spectrum (cutoff) for every run length
    pk = ExperimentalEnvironment(hs, NoiseType.PINK, T2S=t_ref, TJS=t_ref, duration=pink_len,
                                 segment_duration=pink_len, seed=_seed(base_seed, realization, 2))

    def take(tts):
        return [np.asarray(t.values[:length], dtype=float).copy() for t in tts]

    return UnitTraces(freq={"quasistatic": take(qs.time_traces), "white": take(wh.time_traces),
                            "pink": take(pk.time_traces)}, coupling=take(pk.time_traces_coupling))


def bundle_for(unit: UnitTraces, noise: NoiseConfig, hs: HardwareSpecs) -> TraceBundle:
    gam = noise.as_dict()
    scale = {s: (gam[s] * 1e-3 / _GAMMA_REF) ** _EXPONENT[s] if gam[s] > 0 else 0.0 for s in SOURCES}
    n_q = len(unit.freq["pink"])
    freq = [sum(scale[s] * unit.freq[s][q] for s in ("quasistatic", "white", "pink")) for q in range(n_q)]
    return TraceBundle(hs, freq, [scale["exchange"] * c for c in unit.coupling])


