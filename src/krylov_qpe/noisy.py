# Trajectories
# ---------------------------------------------------------------------------


def _block_unitary(block: Block, bundle: TraceBundle | None, t_start: int) -> np.ndarray:
    if bundle is not None:
        block.pulse.t_lab = t_start
        block.pulse.attach_time_traces(bundle)
    return Operator.from_circuit(block.pulse.to_circuit()).data


def trajectory_g(compiled: CompiledHadamardTest, k_max: int, bundle: TraceBundle | None) -> np.ndarray:
    """g(k tau), k = 0..k_max, for one noise realization (bundle=None: noiseless pulses)."""
    tp, ts = compiled.prep.duration_ns, compiled.step.duration_ns
    if bundle is None:
        # fresh pulse circuits: no traces attached
        prep = PulseCircuit.from_circuit(compiled.prep.isa, compiled.hs)
        step = PulseCircuit.from_circuit(compiled.step.isa, compiled.hs)
        u_step = Operator.from_circuit(step.to_circuit()).data
        state = Operator.from_circuit(prep.to_circuit()).data[:, 0]
        out = np.empty(k_max + 1, complex)
        out[0] = 1.0
        for m in range(k_max):
            state = u_step @ state
            out[m + 1] = g_from_state(state)
        return out
    state = _block_unitary(compiled.prep, bundle, 0)[:, 0]
    out = np.empty(k_max + 1, complex)
    out[0] = 1.0
    for m in range(k_max):
        state = _block_unitary(compiled.step, bundle, tp + m * ts) @ state
        out[m + 1] = g_from_state(state)
    return out


def _chunk(compiled, k_max, configs, start, stop, base_seed, fast, spinpulse_fix):
    from . import fast_propagate

    fast_propagate.enable() if fast else fast_propagate.disable()  # per worker process
    spinpulse_patch.apply() if spinpulse_fix else spinpulse_patch.remove()  # per worker process
    # fresh compile per worker process: PulseCircuit objects carry mutable trace state
    local = compile_hadamard_test(compiled.problem, compiled.tau, compiled.hs)
    length = local.run_duration_ns(k_max)
    out = np.empty((len(configs), stop - start, k_max + 1), complex)
    for i, r in enumerate(range(start, stop)):
        unit = generate_unit_traces(local.hs, length, r, base_seed)
        for c, cfg in enumerate(configs):
            out[c, i] = trajectory_g(local, k_max, bundle_for(unit, cfg, local.hs))
    return out


def noisy_g_samples(compiled: CompiledHadamardTest, k_max: int, configs: list[NoiseConfig], n_realizations: int,
                    base_seed: int = 2026, n_jobs: int | None = None, fast: bool = True, spinpulse_fix: bool = True,
                    first_realization: int = 0) -> np.ndarray:
    """Per-realization g, shape (n_configs, n_realizations, k_max + 1). Realization r is shared by all configs.

    Realizations first_realization .. first_realization + n_realizations - 1 are simulated, so
    a long run can be split into blocks with identical results.
    ``fast`` uses the exact accelerated integrator from fast_propagate (False: SpinPulse's own).
    """
    n_jobs = n_jobs or os.cpu_count() or 1
    n_chunks = max(1, min(n_realizations, 4 * n_jobs))
    edges = first_realization + np.linspace(0, n_realizations, n_chunks + 1).astype(int)
    parts = Parallel(n_jobs=n_jobs)(
        delayed(_chunk)(compiled, k_max, configs, a, b, base_seed, fast, spinpulse_fix)
        for a, b in zip(edges[:-1], edges[1:]) if b > a
    )
    return np.concatenate(parts, axis=1)
